"""Reproduce a complete recorded training stall to inspect feasible recovery.

Actions are replayed only after checking the actual recorded observation,
mask and sensor time. Physical poses are generated by the simulator, never
substituted into actor inputs. This is diagnostic initialization, not a
deterministic learned-policy score or a successful demonstration.
"""
import argparse
import hashlib
import json
from pathlib import Path
from unittest.mock import patch

import numpy as np
import torch

from experiments.evaluate_docking_navigation import evaluate
from neural_navigation.decision_feedback_runtime import StopFeedbackRuntime
from neural_navigation.experiment_budget import ExperimentBudget
from neural_navigation.masked_actions import ACTIONS, COMMANDS, masks_from_observation
from navrl.geometry import ROOT


def episode(root, case_id):
    selected, current, hashes = [], [], {}
    for path in sorted((root/'rollouts').glob('*.npz')):
        with np.load(path, allow_pickle=False) as data:
            hashes[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
            for i, raw in enumerate(data['execution_diagnostics_json'][:, 0]):
                label = json.loads(str(raw))
                case = json.loads(label['case_json'])
                if bool(data['episode_starts'][i, 0]):
                    if current and not current[-1]['label']['done']:
                        raise ValueError('Skipped an unfinished recorded episode')
                    current = []
                current.append(dict(observation=data['observations'][i, 0].copy(),
                    mask=data['action_masks'][i, 0].astype(bool), label=label))
                if label['done'] and case.get('source_training_case_id') == case_id:
                    if selected:
                        raise ValueError('Choose an unambiguous recorded case')
                    selected = current.copy()
    if not selected or not selected[-1]['label']['done']:
        raise ValueError('A complete recorded episode is required')
    if selected[0]['label']['sensor_timestamp'] != 0.:
        raise ValueError('A routine episode starting from reset is required')
    specification = json.loads(selected[0]['label']['case_json'])
    scene = Path(specification['scene'])
    try:
        scene = scene.relative_to(ROOT)
    except ValueError:
        # Historical absolute locations are provenance, not destination paths.
        parts = scene.parts
        if 'training' not in parts:
            raise ValueError('Expected a recorded repository training scene')
        scene = Path(*parts[parts.index('training')+1:])
    if '..' in scene.parts or not (ROOT/scene/'decision_map.yaml').is_file():
        raise ValueError('Training scene is not available in the checkout')
    case = dict(id=case_id, scene=str(scene), seed=specification['seed'],
        start=specification['options']['start'], goal=specification['options']['goal'],
        max_steps=len(selected), pilot_category='recorded_training_stall',
        **specification['interventions'])
    if 'initial_prior_offset' in specification['options']:
        case['initial_prior_offset'] = specification['options']['initial_prior_offset']
    return selected, case, hashes


class RecordedTrainingActor:
    def __init__(self, core, records):
        self.core, self.records, self.cursor = core, records, 0

    def predict(self, observation):
        row = self.records[self.cursor]
        x = np.asarray(observation, np.float32)
        if x.shape != (439,):
            raise ValueError('The same V2 directional feedback contract is required')
        actual = np.r_[x[:300], x[303:]]
        if abs(self.core.elapsed-row['label']['sensor_timestamp']) > 1e-8:
            raise ValueError('Recorded sensor time was not reproduced')
        np.testing.assert_allclose(actual, row['observation'], atol=2e-6, rtol=0)
        mask = masks_from_observation(x[:282])
        np.testing.assert_array_equal(mask, row['mask'])
        choice = int(row['label']['sampled_choice'])
        if not mask[choice]:
            raise ValueError('The replay would force an inadmissible command')
        np.testing.assert_allclose(COMMANDS[choice], row['label']['executed_command'], atol=2e-8, rtol=0)
        self.cursor += 1
        return ACTIONS[choice].copy()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['model-run', 'bundle', 'output']:
        parser.add_argument('--'+name, type=Path, required=True)
    parser.add_argument('--case-id', default='train_failure_w11_e7')
    parser.add_argument('--limit-frames', type=int, help='Observation parity smoke only; not a full stall reconstruction')
    parser.add_argument('--cpu-cores', type=float, default=.15)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    torch.set_num_threads(1)
    budget = ExperimentBudget(args.cpu_cores, directory=args.output)
    records, case, hashes = episode(args.model_run, args.case_id)
    complete_frames = len(records)
    if args.limit_frames is not None:
        if not 1 <= args.limit_frames < complete_frames:
            parser.error('Smoke frame count must be strictly within the episode')
        case['max_steps'] = args.limit_frames
    created = []

    class Runtime(StopFeedbackRuntime):
        def __init__(self, *a, **kw):
            super().__init__(*a, **kw)
            actor = RecordedTrainingActor(self.core, records)
            self.policy.policy = actor
            created.append(actor)

    from experiments.experiment_provenance import record_provenance
    record_provenance(args.output, args.bundle)
    (args.output/'case.json').write_text(json.dumps(case, indent=2)+'\n')
    with patch('neural_navigation.goal_pose_runtime.resolve_runtime', return_value=Runtime):
        row, trace = evaluate(case, args.bundle, budget)
    expected = case['max_steps']
    if len(created) != 1 or created[0].cursor != expected or len(trace['choices']) != expected:
        raise ValueError('Training replay ended before the requested frames')
    path = args.output/(case['id']+'.npz')
    np.savez_compressed(path, **trace)
    row.update(variant='recorded_training_actions', trace_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        diagnostic_replay=True, not_a_trained_policy_score=True,
        actual_training_observations_masks_commands_and_sensor_times_verified=True)
    report = dict(completed=True, full_replay=args.limit_frames is None,
        replayed_frames=expected, complete_episode_frames=complete_frames,
        actual_training_rollout_sha256=hashes, rows=[row], case=case,
        deployment_approved=False, resource=budget.statistics(),
        limitations=['Commands replay actual stochastic training choices; this is not a fresh learned-policy test.',
            'Original training records did not save physical poses; new physical labels come from deterministic sensor/action replay.',
            'A stalled or failed episode must not be treated as a successful demonstration.'])
    (args.output/'RESULTS.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report, indent=2), flush=True)


if __name__ == '__main__':
    main()
